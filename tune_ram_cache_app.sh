#!/usr/bin/env bash
set -euo pipefail

###############################################################################
# RAM + cache settings for the ClickHouse server nodes, computed from each node's real RAM.
#   Usage: tune_ram_cache_app.sh [--restart] [inventory.txt]
#
#   Writes 2 files (re-running setup_1s3r_airgap_app.sh does NOT overwrite them):
#     ${APP_BASE}/clickhouse-server/config.d/memory.xml         (server: total RAM, caches)
#     ${APP_BASE}/clickhouse-server/users.d/profile_memory.xml  (default profile: RAM per query/user)
#   Default is SYSTEM RELOAD CONFIG only. --restart: restart nodes one by one, the next node
#   only after the previous one answers SELECT 1 (the cluster always has replicas serving).
###############################################################################
BASE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
LOG_DIR="${BASE_DIR}/logs"
RESTART=0
INVENTORY_FILE="${BASE_DIR}/inventory.txt"

for arg in "$@"; do
  case "${arg}" in
    --restart) RESTART=1 ;;
    -*) echo "ERROR: unsupported option '${arg}'" >&2; exit 1 ;;
    *) INVENTORY_FILE="${arg}" ;;
  esac
done

mkdir -p "${LOG_DIR}"
LOG_FILE="${LOG_DIR}/tune_ram_cache_$(date +%Y%m%d_%H%M%S).log"
exec > >(tee -a "${LOG_FILE}") 2>&1

die() {
  echo "ERROR: $*" >&2
  exit 1
}

###############################################################################
# RATIOS (% of node RAM)
###############################################################################
SERVER_RAM_RATIO="0.8"      # ClickHouse uses at most 80% of RAM, the rest is for the OS + page cache
MARK_CACHE_PCT=8            # mark cache          (128G -> ~10G)
QUERY_PCT=25                # RAM per query      (128G -> 32G)
USER_PCT=50                 # RAM per user       (128G -> 64G)
SPILL_PCT=12                # GROUP BY/ORDER BY spill to disk above this (~1/2 of per-query RAM)

MIN_MARK_CACHE=$((5 * 1024 * 1024 * 1024))           # never below the 5 GiB default
UNCOMPRESSED_CACHE=$((2 * 1024 * 1024 * 1024))       # kept small, use_uncompressed_cache=0
QUERY_CACHE=$((4 * 1024 * 1024 * 1024))              # for dashboards repeating the same queries
QUERY_CACHE_ENTRY=$((100 * 1024 * 1024))

RESTART_WAIT_SEC=180

###############################################################################
# INVENTORY (only APP_BASE + the server lines are needed)
###############################################################################
APP_BASE=""
CH_NODES=()
CH_HOSTS=()

load_inventory() {
  local line key val role ip hn
  [[ -f "${INVENTORY_FILE}" ]] || die "Inventory not found: ${INVENTORY_FILE}"

  while IFS= read -r line || [[ -n "${line}" ]]; do
    line="${line//$'\r'/}"
    line="${line%%#*}"
    [[ -n "${line//[[:space:]]/}" ]] || continue

    if [[ "${line}" == *=* ]]; then
      read -r key <<< "${line%%=*}"
      read -r val <<< "${line#*=}"
      [[ "${key}" == "APP_BASE" ]] && APP_BASE="${val%/}"
      continue
    fi

    read -r role ip hn _ <<< "${line}"
    if [[ "${role}" == "server" ]]; then
      CH_NODES+=("${ip}")
      CH_HOSTS+=("${hn}")
    fi
  done < "${INVENTORY_FILE}"

  [[ "${APP_BASE}" =~ ^/[A-Za-z0-9._/-]+$ ]] || die "${INVENTORY_FILE}: APP_BASE='${APP_BASE}' is invalid"
  (( ${#CH_NODES[@]} >= 1 )) || die "${INVENTORY_FILE}: no server line found"
}

load_inventory

CH_ETC="${APP_BASE}/clickhouse-server"
CH_CFGD="${CH_ETC}/config.d"
CH_USERSD="${CH_ETC}/users.d"

###############################################################################
# SSH
###############################################################################
SSH_USER="root"
SSH_OPTS="-o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null"

# SSH_OPTS is word-split on purpose; remote commands are built on this side on purpose
# shellcheck disable=SC2086,SC2029
ssh_run() {
  ssh ${SSH_OPTS} "${SSH_USER}@${1}" "${@:2}"
}

gib() {
  awk -v b="$1" 'BEGIN { printf "%.1f GiB", b / 1073741824 }'
}

###############################################################################
# XML
###############################################################################
gen_memory_xml() {
  local mark_cache="$1"
cat <<EOF
<clickhouse>
  <!-- generated by tune_ram_cache_app.sh -->
  <max_server_memory_usage_to_ram_ratio>${SERVER_RAM_RATIO}</max_server_memory_usage_to_ram_ratio>

  <mark_cache_size>${mark_cache}</mark_cache_size>
  <uncompressed_cache_size>${UNCOMPRESSED_CACHE}</uncompressed_cache_size>

  <query_cache>
    <max_size_in_bytes>${QUERY_CACHE}</max_size_in_bytes>
    <max_entries>1024</max_entries>
    <max_entry_size_in_bytes>${QUERY_CACHE_ENTRY}</max_entry_size_in_bytes>
    <max_entry_size_in_rows>30000000</max_entry_size_in_rows>
  </query_cache>
</clickhouse>
EOF
}

gen_profile_xml() {
  local per_query="$1" per_user="$2" spill="$3"
cat <<EOF
<clickhouse>
  <!-- generated by tune_ram_cache_app.sh; overrides the default profile in users.xml -->
  <profiles>
    <default>
      <max_memory_usage>${per_query}</max_memory_usage>
      <max_memory_usage_for_user>${per_user}</max_memory_usage_for_user>
      <max_bytes_before_external_group_by>${spill}</max_bytes_before_external_group_by>
      <max_bytes_before_external_sort>${spill}</max_bytes_before_external_sort>
      <use_uncompressed_cache>0</use_uncompressed_cache>
    </default>
  </profiles>
</clickhouse>
EOF
}

VERIFY_SERVER_SQL="
SELECT name, value, changeable_without_restart
FROM system.server_settings
WHERE name IN ('max_server_memory_usage', 'max_server_memory_usage_to_ram_ratio',
               'mark_cache_size', 'uncompressed_cache_size')
ORDER BY name
FORMAT PrettyCompactMonoBlock"

VERIFY_PROFILE_SQL="
SELECT name, value
FROM system.settings
WHERE name IN ('max_memory_usage', 'max_memory_usage_for_user',
               'max_bytes_before_external_group_by', 'max_bytes_before_external_sort',
               'use_uncompressed_cache')
ORDER BY name
FORMAT PrettyCompactMonoBlock"

wait_ready() {
  local ip="$1" waited=0
  until ssh_run "$ip" "clickhouse-client -q 'SELECT 1'" >/dev/null 2>&1; do
    (( waited < RESTART_WAIT_SEC )) || die "[${ip}] clickhouse-server not up after ${RESTART_WAIT_SEC}s, stopping so the remaining nodes keep serving"
    sleep 5
    waited=$((waited + 5))
  done
}

###############################################################################
# APPLY
###############################################################################
echo "==> Inventory: ${INVENTORY_FILE} (APP_BASE=${APP_BASE})"

for ((i = 0; i < ${#CH_NODES[@]}; i++)); do
  ip="${CH_NODES[i]}"
  hn="${CH_HOSTS[i]}"

  ssh_run "$ip" "test -d ${CH_CFGD} && test -d ${CH_USERSD}" \
    || die "[${ip}] missing ${CH_CFGD} or ${CH_USERSD}, run setup_1s3r_airgap_app.sh first"

  mem_kb="$(ssh_run "$ip" "awk '/^MemTotal:/ {print \$2}' /proc/meminfo")"
  [[ "${mem_kb}" =~ ^[0-9]+$ ]] || die "[${ip}] cannot read MemTotal: '${mem_kb}'"
  ram=$((mem_kb * 1024))

  mark_cache=$((ram * MARK_CACHE_PCT / 100))
  (( mark_cache >= MIN_MARK_CACHE )) || mark_cache=${MIN_MARK_CACHE}
  per_query=$((ram * QUERY_PCT / 100))
  per_user=$((ram * USER_PCT / 100))
  spill=$((ram * SPILL_PCT / 100))

  echo "==> [${ip}] ${hn}: RAM $(gib "${ram}")"
  echo "    server limit  : ${SERVER_RAM_RATIO} x RAM"
  echo "    mark cache    : $(gib "${mark_cache}")"
  echo "    per query     : $(gib "${per_query}")"
  echo "    per user      : $(gib "${per_user}")"
  echo "    spill to disk : $(gib "${spill}")"

  ssh_run "$ip" "cat > ${CH_CFGD}/memory.xml <<'EOF'
$(gen_memory_xml "${mark_cache}")
EOF
chown clickhouse:clickhouse ${CH_CFGD}/memory.xml && chmod 640 ${CH_CFGD}/memory.xml"

  ssh_run "$ip" "cat > ${CH_USERSD}/profile_memory.xml <<'EOF'
$(gen_profile_xml "${per_query}" "${per_user}" "${spill}")
EOF
chown clickhouse:clickhouse ${CH_USERSD}/profile_memory.xml && chmod 640 ${CH_USERSD}/profile_memory.xml"

  if (( RESTART )); then
    echo "==> [${ip}] restart clickhouse-server"
    ssh_run "$ip" "systemctl restart clickhouse-server"
    wait_ready "$ip"
  else
    echo "==> [${ip}] SYSTEM RELOAD CONFIG"
    ssh_run "$ip" "clickhouse-client -q 'SYSTEM RELOAD CONFIG'"
  fi

  echo "==> [${ip}] verify"
  ssh_run "$ip" "clickhouse-client -q \"${VERIFY_SERVER_SQL}\""
  ssh_run "$ip" "clickhouse-client -q \"${VERIFY_PROFILE_SQL}\""
done

cat <<EOF

RAM/CACHE CONFIG APPLIED
=================================
The effective RAM limit is max_server_memory_usage (applied on reload).
max_server_memory_usage_to_ram_ratio keeps showing the old value until the next
restart; to make it match now, re-run with --restart (one node at a time).
LOG FILE: ${LOG_FILE}

EOF
